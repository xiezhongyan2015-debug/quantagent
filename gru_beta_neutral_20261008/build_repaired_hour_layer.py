"""Build an isolated historical hourly repair layer, never invent minute bars.

Admission requires successful withheld controls and an intact original minute
grid, with exactly one known corrupt boundary. Full-day independent sources
calibrate the historical price adjustment; these are after-the-fact repairs,
not a prospective minute feed. Execution observations are kept unchanged.
"""
import hashlib
import json
import sys
from pathlib import Path
from reconstruct_2019_boundaries import OUT, ROOT, pq, pd, np
sys.path.insert(0,str(ROOT))
from gru_research.minute_data import aggregate_stock_day, HOUR_FEATURES, _ratio


def valid80(complete):
    prefix=np.vstack([np.zeros((1,complete.shape[1]),dtype=np.int32),np.cumsum(~complete,axis=0,dtype=np.int32)])
    result=np.zeros_like(complete)
    result[79:]=prefix[80:]==prefix[:-80]
    return result


def main():
    control=json.loads((OUT/'2019_boundary_withheld_validation_receipt.json').read_text())
    recovery_path=Path(__file__).parent/'reconstruct_2019_boundaries.py'
    assert control['validation_passed'] and control['ohlc_mismatches']==0
    assert control['recovery_source_sha256']==hashlib.sha256(recovery_path.read_bytes()).hexdigest()
    candidate=pd.read_csv(OUT/'2019_hour_boundary_recovery.csv')
    candidate=candidate[candidate.status.eq('verified_hour_boundary_recovery')]
    rows=[];rejected=[]
    for item in candidate.to_dict('records'):
        day,symbol=item['date'],item['symbol'];path=OUT/'minute_original_selected'/day/(symbol+'.parquet')
        payload=path.read_bytes()
        assert hashlib.sha256(payload).hexdigest()==item['original_payload_sha256']
        original,audit=aggregate_stock_day((day,symbol,payload))
        x=pq.read_table(path).to_pandas()
        if (len(original)!=4 or audit['error'] or audit['invalid_rows']!=1 or audit['qfq_mismatch_rows']
            or audit['duplicate_rows'] or audit['timestamp_mismatch_rows'] or audit['outside_session_rows']
            or len(x)!=240 or x.open.iloc[0]!=0 or x.low.iloc[0]!=0 or x.volume.iloc[:60].sum()<=0):
            rejected.append({'date':day,'symbol':symbol,'reason':'original_minute_admission_guard','audit':audit});continue
        assert not original[0]['hour_complete']
        raw=np.array([item['raw_open'],item['raw_high'],item['raw_low'],item['raw_close']])
        factor=float(x.qfq_ratio.iloc[0]);o,h,l,c=raw*factor
        assert np.isfinite(raw).all() and raw.min()>0 and h>=max(o,c,l) and l<=min(o,c,h)
        closes=x.qfq_close.iloc[:60].to_numpy();v=x.volume.iloc[:60].to_numpy()
        minute_r=np.log(closes/np.r_[o,closes[:-1]])
        sr=float(np.square(minute_r).sum());std=minute_r.std();logv=np.log1p(v)
        corr=float(np.corrcoef(minute_r,logv)[0,1]) if std>1e-12 and logv.std()>1e-12 else np.nan
        pathlength=float(np.abs(np.diff(np.r_[o,closes])).sum())
        stats=[np.sqrt(sr),float(np.mean(((minute_r-minute_r.mean())/std)**3)) if std>1e-12 else np.nan,
               minute_r.max(),minute_r.min(),_ratio(np.square(minute_r[minute_r>0]).sum(),sr),corr,
               _ratio(v[-15:].sum(),v.sum()),float(np.mean(v==0)),_ratio(abs(c-o),pathlength),
               _ratio(v[minute_r>0].sum(),v.sum())]
        row=dict(original[0]);row.update(dict(zip(HOUR_FEATURES[14:],stats)))
        row.update(hour_complete=True,open=o,high=h,low=l,close=c,volume=float(v.sum()),
                   raw_open=raw[0],raw_high=raw[1],raw_low=raw[2],raw_close=raw[3],adjustment_factor=factor,
                   boundary_recovered=True,original_invalid_minute_rows=1,minute_source_fully_valid=False,
                   source_original_sha256=item['original_payload_sha256'],
                   price_low_basis='Unique hourly value under independent affine-adjustment constraints',
                   recovery_uses_full_day_for_source_calibration=True)
        # No new executable observation is generated by this repair.
        assert row['window_price']==original[0]['window_price'] or (np.isnan(row['window_price']) and np.isnan(original[0]['window_price']))
        rows.append(row)
    frame=pd.DataFrame(rows);destination=OUT/'repaired_2019_hour_layer.parquet'
    frame.to_parquet(destination,index=False)
    (OUT/'repaired_2019_hour_rejected.json').write_text(json.dumps(rejected,ensure_ascii=False,indent=2))
    dataset=ROOT/'gru_research/artifacts/dataset';symbols=json.loads((dataset/'symbols.json').read_text())
    times=np.load(dataset/'times.npy');members=np.load(dataset/'members.npy')
    base=np.load(dataset/'hour_complete.npy');repaired=base.copy()
    time_index={int(t):i for i,t in enumerate(times)};symbol_index={s:i for i,s in enumerate(symbols)}
    applied=0
    for row in rows:
        t=time_index[row['signal_time']];n=symbol_index[row['symbol']]
        assert not base[t,n];repaired[t,n]=True;applied+=1
    old=valid80(base);new=valid80(repaired);years=pd.to_datetime(times,utc=True).tz_convert('Asia/Shanghai').year
    coverage=[]
    for year in sorted(set(years)):
        mask=years==year;denominator=int(members[mask].sum())
        old_count=int((old[mask]&members[mask]).sum());new_count=int((new[mask]&members[mask]).sum())
        coverage.append({'year':int(year),'pool_stock_hours':denominator,'original_complete_80_hours':old_count,
                         'repair_layer_complete_80_hours':new_count,'newly_available_stock_hours':new_count-old_count,
                         'original_coverage':old_count/denominator,'repair_layer_coverage':new_count/denominator})
    pd.DataFrame(coverage).to_csv(OUT/'2019_repair_layer_coverage_counterfactual.csv',index=False)
    np.save(OUT/'hour_complete_with_2019_repair_layer.npy',repaired)
    receipt={'status':'isolated_hour_layer_ready_for_reassembly_review','candidate_rows':len(candidate),
             'admitted_hour_rows':len(frame),'rejected_rows':len(rejected),'counterfactual_hour_flags_applied':applied,
             'coverage_counterfactual':coverage,'output_sha256':hashlib.sha256(destination.read_bytes()).hexdigest(),
             'original_dataset_modified':False,'new_X_or_labels_built':False,'source_minute_bars_invented':False,
             'execution_prices_modified':False,'suspension_rows_repaired':False,
             'limitation':'This layer repairs hourly boundaries only; it is not a complete replacement minute archive. Coverage is a structural 80-hour counterfactual, pending full feature and label reassembly.',
             'validation_receipt_sha256':hashlib.sha256((OUT/'2019_boundary_withheld_validation_receipt.json').read_bytes()).hexdigest(),
             'boundary_receipt_sha256':hashlib.sha256((OUT/'2019_hour_boundary_recovery_receipt.json').read_bytes()).hexdigest()}
    (OUT/'2019_repaired_hour_layer_receipt.json').write_text(json.dumps(receipt,ensure_ascii=False,indent=2))
    print(json.dumps(receipt,ensure_ascii=False))


if __name__=='__main__':main()
